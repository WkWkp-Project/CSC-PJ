def main() -> int:
    entries = []
    mismatches = []
    self_answer = human_assist = 0
    for intent, slug, question, keywords, answer, needs, safety in SPECS:
        result = classify_v2(question, "")
        predicted = {result["primary_intent"], *result["secondary_intents"]}
        if intent not in predicted:
            mismatches.append((slug, intent, result["primary_intent"], question))
            continue
        route = result["route"]
        mode = "self_answer_candidate" if route == "KB_CANDIDATE_HOLD" else "human_assist"
        if mode == "self_answer_candidate":
            self_answer += 1
        else:
            human_assist += 1
        entry = {
            "id": f"faq-{intent}-{slug}",
            "intents": [intent],
            "keywords": keywords,
            "question": question,
            "answer_draft": answer,
            "needs_brand_input": needs,
            "answer_mode": mode,
            "classifier_route": route,
            "routing_verified": True,
            "source": "chat_research_messenger_line",
            "status": "draft",
            "approved": False,
            "approved_by": None,
        }
        if safety:
            entry["safety_note"] = safety
        entries.append(entry)

    if mismatches:
        print("ROUTING MISMATCHES (fix question/keywords):", file=sys.stderr)
        for slug, declared, got, q in mismatches:
            print(f"  {slug}: declared={declared} got={got} :: {q}", file=sys.stderr)
        return 1

    doc = {
        "schema_version": "phase6-kb-draft-v1",
        "answer_generation_enabled": False,
        "generated_by": "phase8/build_kb_draft.py",
        "status_note": (
            "ALL entries are status=draft / approved=false. The engine loads ONLY "
            "status=published AND approved=true, so nothing here is served to a customer "
            "until the brand fills the «...» facts and promotes it into approved_kb.json. "
            "Questions/keywords are from chat research and VERIFIED against classify_v2. "
            "answer_mode=self_answer_candidate means the engine can auto-answer it once "
            "approved; human_assist means it routes to a person and the draft just speeds "
            "the human reply."
        ),
        "excluded_from_self_answer": {
            "note": "Never given self-answer FAQ - always human, because a wrong answer is harmful or binding.",
            "I03": "แพ้/เจ/ฮาลาล/วีแกน/โลหะหนัก/เบาหวาน - personal safety + formal product claim (H2).",
            "I07": "ขายส่ง/ราคาส่ง/ขั้นต่ำ - commercial terms (Sales/H2).",
            "I14": "ร้องเรียนคุณภาพ/สินค้าเสีย - complaint + possible claim (H2).",
        },
        "counts": {
            "total": len(entries),
            "self_answer_candidate": self_answer,
            "human_assist": human_assist,
        },
        "entries": entries,
    }
    OUT.write_text(json.dumps(doc, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"wrote {len(entries)} entries -> {OUT}")
    print(f"  self_answer_candidate (engine can auto-answer once approved): {self_answer}")
    print(f"  human_assist (routes to a person; draft speeds the reply):    {human_assist}")
    by_intent = {}
    for e in entries:
        by_intent[e["intents"][0]] = by_intent.get(e["intents"][0], 0) + 1
    print("  by intent:", json.dumps(by_intent, ensure_ascii=False))
    return 0


